using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using Bw.Entities.Network;
using NUnit.Framework;
using Unity.Netcode;
using UnityEditor.Compilation;
using Assembly = System.Reflection.Assembly;

namespace Bw.Tests.Integration.Network
{
    public sealed class CodecRegistryTests
    {
        private const string RegistryPath = "Assets/Game/Scripts/Injection/Network/MessageHandlersInstaller.Generated.cs";

        private static readonly Regex Registration = new(@"^\s*RegisterCodec<(.+)>\(receivers, senders\);\s*$", RegexOptions.Multiline);

        [Test]
        public void RegistryListsEveryCodecOfTheGameAndNothingElse()
        {
            var discovered = Codecs().Select(codec => Spec(codec.Codec)).ToList();

            var registered = Registrations().Select(registration => registration.Codec).ToList();

            Assert.That(registered, Is.EquivalentTo(discovered));
        }

        [Test]
        public void RegistrationsAreOrderedByTheCodecsFullName()
        {
            var registered = Registrations().Select(registration => registration.Codec).ToList();

            var byFullName = Codecs().OrderBy(codec => codec.Codec.FullName, StringComparer.Ordinal).Select(codec => Spec(codec.Codec)).ToList();

            Assert.That(registered, Is.EqualTo(byFullName));
        }

        [Test]
        public void EveryPayloadHasOneCodec()
        {
            var payloads = Codecs().GroupBy(codec => codec.Payload).Where(group => group.Count() > 1)
                .Select(group => $"{group.Key.FullName}: {string.Join(", ", group.Select(codec => codec.Codec.FullName))}")
                .ToList();

            Assert.That(payloads, Is.Empty, string.Join("\n", payloads));
        }

        [Test]
        public void RegistryPairsEveryCodecWithItsOwnPayload()
        {
            var pairs = Codecs().ToDictionary(codec => Spec(codec.Codec), codec => Spec(codec.Payload));

            var mismatched = Registrations().Where(registration => !pairs.TryGetValue(registration.Codec, out var payload) || payload != registration.Payload)
                .Select(registration => $"{registration.Payload} with {registration.Codec}")
                .ToList();

            Assert.That(mismatched, Is.Empty, string.Join("\n", mismatched));
        }

        [Test]
        public void RegistryIsWhatTheGeneratorWrites()
        {
            var written = Normalized(File.ReadAllText(Path.GetFullPath(RegistryPath)));

            var generated = Normalized(Generated());

            Assert.That(written, Is.EqualTo(generated));
        }

        private static string Generated()
        {
            var text = new StringBuilder();
            text.AppendLine("// <auto-generated />");
            text.AppendLine("// Regenerate: Unity menu Tools → Network → Regenerate message codec registrations");
            text.AppendLine();
            text.AppendLine("namespace Bw.Injection.Network");
            text.AppendLine("{");
            text.AppendLine("    public partial class MessageHandlersInstaller");
            text.AppendLine("    {");
            text.AppendLine("        partial void RegisterGeneratedMessageCodecs(");
            text.AppendLine("            System.Collections.Generic.Dictionary<System.Type, Bw.Entities.Network.IMessageReceiver> receivers,");
            text.AppendLine("            System.Collections.Generic.Dictionary<System.Type, Bw.Entities.Network.IMessageSender> senders)");
            text.AppendLine("        {");
            foreach (var codec in Codecs().OrderBy(codec => codec.Codec.FullName, StringComparer.Ordinal))
                text.AppendLine($"            RegisterCodec<{Spec(codec.Payload)}, {Spec(codec.Codec)}>(receivers, senders);");

            text.AppendLine("        }");
            text.AppendLine("    }");
            text.AppendLine("}");
            return text.ToString();
        }

        private static string Normalized(string text) =>
            text.Replace("\r\n", "\n");

        private static List<(string Payload, string Codec)> Registrations()
        {
            var registrations = new List<(string Payload, string Codec)>();
            foreach (Match match in Registration.Matches(Normalized(File.ReadAllText(Path.GetFullPath(RegistryPath)))))
            {
                var arguments = TopLevelArguments(match.Groups[1].Value);
                Assert.That(arguments, Has.Count.EqualTo(2), match.Value);
                registrations.Add((arguments[0], arguments[1]));
            }

            return registrations;
        }

        private static List<string> TopLevelArguments(string arguments)
        {
            var split = new List<string>();
            var depth = 0;
            var start = 0;
            for (var index = 0; index < arguments.Length; index++)
            {
                depth += arguments[index] == '<' ? 1 : arguments[index] == '>' ? -1 : 0;
                if (arguments[index] != ',' || depth != 0)
                    continue;

                split.Add(arguments.Substring(start, index - start).Trim());
                start = index + 1;
            }

            split.Add(arguments.Substring(start).Trim());
            return split;
        }

        private static List<(Type Payload, Type Codec)> Codecs()
        {
            var codecs = new List<(Type Payload, Type Codec)>();
            var player = new HashSet<string>(CompilationPipeline.GetAssemblies(AssembliesType.Player).Select(assembly => assembly.name).Where(name => name.StartsWith("Bw.")));
            foreach (var assembly in AppDomain.CurrentDomain.GetAssemblies().Where(assembly => !assembly.IsDynamic && player.Contains(assembly.GetName().Name)))
                foreach (var type in TypesOf(assembly))
                {
                    if (!type.IsValueType || type.IsEnum || type.IsAbstract || type.ContainsGenericParameters || !typeof(INetworkSerializable).IsAssignableFrom(type))
                        continue;

                    var codec = type.GetInterfaces().FirstOrDefault(contract => contract.IsGenericType && contract.GetGenericTypeDefinition() == typeof(ICodec<>));
                    if (codec != null)
                        codecs.Add((codec.GetGenericArguments()[0], type));
                }

            return codecs;
        }

        private static IEnumerable<Type> TypesOf(Assembly assembly)
        {
            try
            {
                return assembly.GetTypes();
            }
            catch (ReflectionTypeLoadException exception)
            {
                return exception.Types.Where(type => type != null);
            }
        }

        private static string Spec(Type type)
        {
            var name = type.IsNested
                ? $"{Spec(type.DeclaringType)}.{type.Name}"
                : string.IsNullOrEmpty(type.Namespace)
                    ? type.Name
                    : $"{type.Namespace}.{type.Name}";

            if (!type.IsGenericType)
                return name;

            return $"{name.Substring(0, name.IndexOf('`'))}<{string.Join(", ", type.GetGenericArguments().Select(Spec))}>";
        }
    }
}
