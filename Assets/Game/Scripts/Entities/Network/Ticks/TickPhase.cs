namespace Bw.Entities.Network.Ticks
{//TODO: переписать с нейрослопного на человеческий
    //Внимание: порядок значений — это порядок фаз внутри тика. Перестановка значений или добавление новых меняет,
    //в каком порядке системы видят друг друга в тике, и может повлиять на игровой процесс
    //
    //Каждый тик фазы срабатывают строго по порядку значений: на сервере — для серверного тика, на клиенте — для его
    //предсказанного тика (он идёт впереди сервера). Внутри одной фазы порядок подписчиков не задан, полагаться на него
    //нельзя: всё, что в том же тике должно идти после чего-то другого, выносится в более позднюю фазу.
    //Чужие объекты на клиенте в фазах не шагают — их показывает интерполяция в кадре, на InterpolationTick.
    //Новая фаза — это новое значение; номера идут 0, 1, 2… по порядку, это проверяет TickPhaseSignals
    public enum TickPhase
    {
        //Мир по расписанию: объекты, чья поза — чистая функция номера тика (лифт, паллета крана). Они встают в позу
        //этого тика раньше всех, чтобы симуляции в Default видели мир именно этого тика.
        //Сюда: только постановку таких объектов по номеру тика, одинаково на обоих пирах; на клиенте ещё — постановку
        //тел, которые двигает его предсказание (ящик, который толкает свой персонаж), в их состояние перед этим тиком.
        //Нельзя: шагать симуляции и читать состояния тел этого тика — они ещё не шагнули.
        //Всё, что ставится здесь, обязано быть и IScheduled в IScheduledCollection (или IPredictedBody в
        //IPredictedBodyCollection): при пересчёте прошлых тиков сверщик фаз не вызывает, а переставляет такие объекты
        //сам, и на сервере объекты по расписанию переставляет ещё и откат лаг-компенсации
        Early,

        //Шаг симуляций. Клиент снимает ввод своих объектов, отправляет его и шагает их предсказание
        //(PredictionInputSender); сервер берёт ввод этого тика из буфера и шагает симуляцию каждого объекта
        //(PredictionInputBuffer). Тело, которое идёт в ящик, толкает его прямо в своём шаге (IShovable): ящик сдвигается
        //сразу, чтобы тело заняло освободившееся место. Сюда же — счётчики и таймеры в тиках: истечение предсказаний,
        //удаление трупов и брошенного оружия, отчёт о запасе ввода.
        //Нельзя: разбирать взаимодействия, которым нужны все тела на этом тике, — пока шагает одно тело, другие могли
        //ещё не шагнуть. Такие события здесь только копятся (выстрелы встают в очередь резолвера) и разбираются в Late
        Default,

        //Тела без своего ввода (ящики): шагают после Default, где их толкают тела с вводом, и продолжают от толкнутого
        //места, так что их состояние за тик уже включает все толчки этого тика (тяжесть, отброс, езду на платформе).
        //Сюда: шаг таких тел (FreeBody через PassiveStepper).
        //Нельзя: шагать тела с вводом и толкать — толчок отсюда не попадёт в шаг толкнутого тела этого тика
        Passive,

        //Все тела уже на этом тике. Сюда: работу, которой нужен весь мир в одном тике, — на сервере это разбор
        //выстрелов с лаг-компенсацией (RaycastShotResolver: откат к тому, что видел стрелок, каст и итоги).
        //Нельзя: шагать симуляции — тело, шагнувшее здесь, окажется на тик впереди остальных
        Late
    }
}
