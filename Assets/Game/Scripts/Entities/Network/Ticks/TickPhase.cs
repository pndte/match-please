namespace Bw.Entities.Network.Ticks
{
    //Фазы тика по порядку: порядок значений — порядок в тике, и перестановка меняет игру.
    //Prepare и Publish живые: раз в тик, при пересчёте отката не повторяются. Early, Default и Late — шаг мира: клиент повторяет их для каждого пересчитанного тика.
    //Между Prepare и Early клиент откатывает и пересчитывает мир, между Early и Default шагает физика.
    //Порядок подписчиков внутри одной фазы не задан.
    public enum TickPhase
    {
        //До шага: свой ввод снимается и уходит серверу, решается пузырь, непредсказанное принимает состояние сервера, боты думают
        Prepare,

        //Позы по номеру тика (платформы)
        Early,

        //Шаги вводом этого тика и счётчики в тиках
        Default,

        //Взаимодействия, которым нужен весь мир этого тика: выстрелы, удары, броски
        Late,

        //После шага: мир тика окончателен — сервер рассылает состояния и ввод, пишет истории лаг-компенсации
        Publish
    }
}
